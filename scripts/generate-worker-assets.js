const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const viewsDir = path.join(rootDir, 'views');
const localesDir = path.join(rootDir, 'locales');
const outputDir = path.join(rootDir, 'src');
const outputFile = path.join(outputDir, 'worker-assets.cjs');

function walk(dir, predicate) {
  const items = [];
  if (!fs.existsSync(dir)) return items;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      items.push(...walk(fullPath, predicate));
    } else if (!predicate || predicate(fullPath)) {
      items.push(fullPath);
    }
  }
  return items;
}

function toPosixRelative(baseDir, filePath) {
  return path.relative(baseDir, filePath).split(path.sep).join('/');
}

const views = {};
for (const filePath of walk(viewsDir, file => file.endsWith('.ejs'))) {
  views[toPosixRelative(viewsDir, filePath)] = fs.readFileSync(filePath, 'utf8');
}

const locales = {};
for (const filePath of walk(localesDir, file => file.endsWith('.json'))) {
  const rel = toPosixRelative(localesDir, filePath);
  const [language, fileName] = rel.split('/');
  const namespace = path.basename(fileName, '.json');
  locales[language] = locales[language] || {};
  locales[language][namespace] = JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(
  outputFile,
  `// Generated by scripts/generate-worker-assets.js. Do not edit by hand.\nmodule.exports = ${JSON.stringify({ views, locales }, null, 2)};\n`
);

console.log(`Generated ${path.relative(rootDir, outputFile)}`);
