const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const rootDir = path.join(__dirname, '..');
const viewsDir = path.join(rootDir, 'views');
const outputDir = path.join(rootDir, 'src');
const outputFile = path.join(outputDir, 'worker-templates.cjs');
const templateLocals = [
  'title',
  'page',
  'error',
  'metaDescription',
  'metaRobots',
  'metaImage',
  'canonicalUrl',
  'defaultMetaImage',
  'defaultMetaRobots',
  'pageStyles',
  'structuredData',
  'user',
  'i18next',
  't',
  'homeContent',
  'toolPage',
  'modelDetailContent',
  'items',
  'categories',
  'models',
  'catalogModels',
  'catalogTotal',
  'catalogPagination',
  'landingContent',
  'category',
  'resourceType',
  'resourceTypeLabel',
  'related',
  'model',
  'counts',
  'inquiryFilters',
  'inquiryPagination',
  'inquiryStats',
  'articles',
  'article',
  'resources',
  'shareSurface',
  'shareTitle',
  'shareKicker',
  'sharePrompt'
];

function walk(dir, predicate) {
  const items = [];
  if (!fs.existsSync(dir)) return items;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      items.push(...walk(fullPath, predicate));
    } else if (!predicate || predicate(fullPath)) {
      items.push(fullPath);
    }
  }
  return items;
}

function toPosixRelative(baseDir, filePath) {
  return path.relative(baseDir, filePath).split(path.sep).join('/');
}

function compileTemplate(filePath) {
  const rel = toPosixRelative(viewsDir, filePath);
  const source = fs.readFileSync(filePath, 'utf8');
  const template = ejs.compile(source, {
    client: true,
    compileDebug: false,
    _with: false,
    localsName: 'locals',
    destructuredLocals: templateLocals,
    filename: rel
  });
  return [rel, template.toString()];
}

const templates = walk(viewsDir, file => file.endsWith('.ejs'))
  .map(compileTemplate)
  .sort(([a], [b]) => a.localeCompare(b));

const templateEntries = templates
  .map(([rel, fnSource]) => `  ${JSON.stringify(rel)}: ${fnSource}`)
  .join(',\n');

const moduleSource = `// Generated by scripts/generate-worker-templates.js. Do not edit by hand.
const templates = {
${templateEntries}
};

function normalizePath(value) {
  return String(value || '')
    .replace(/\\\\/g, '/')
    .replace(/^\\/+/, '')
    .replace(/\\.ejs$/, '') + '.ejs';
}

function dirname(rel) {
  const index = rel.lastIndexOf('/');
  return index === -1 ? '' : rel.slice(0, index);
}

function joinPath(base, target) {
  const parts = (base ? base + '/' : '') + String(target || '');
  const output = [];
  for (const part of parts.split('/')) {
    if (!part || part === '.') continue;
    if (part === '..') output.pop();
    else output.push(part);
  }
  return output.join('/');
}

function resolveInclude(fromRel, includePath) {
  const candidates = [
    joinPath(dirname(fromRel), includePath),
    String(includePath || '')
  ];
  for (const candidate of candidates) {
    const rel = normalizePath(candidate);
    if (templates[rel]) return rel;
  }
  throw new Error('Worker template include not found: ' + includePath + ' from ' + fromRel);
}

function renderTemplate(rel, locals) {
  const key = normalizePath(rel);
  const template = templates[key];
  if (!template) {
    throw new Error('Worker template not found: ' + rel);
  }

  const data = locals || {};
  return template(data, undefined, (includePath, includeData) => {
    const includeRel = resolveInclude(key, includePath);
    return renderTemplate(includeRel, Object.assign({}, data, includeData || {}));
  });
}

module.exports = {
  render: renderTemplate,
  has: rel => Boolean(templates[normalizePath(rel)]),
  keys: () => Object.keys(templates)
};
`;

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputFile, moduleSource);

console.log(`Generated ${path.relative(rootDir, outputFile)}`);
